if (require.main === module) {
  // Observer controls: control-good validates a known-good observation, control-bad a known-bad
  // one that the fixture must reject at the stop reason (the Go test passes only then).
  const mode = process.argv[2];
  if (mode !== 'control-good' && mode !== 'control-bad') {
    console.log('usage: build-no-edit-turns-end-build__steps.js control-good|control-bad');
    process.exitCode = 2;
  } else {
    const r = run(mode);
    if (r.ok) {
      console.log(mode === 'control-good' ? 'observer accepted' : 'observer rejected');
      process.exitCode = mode === 'control-good' ? 0 : 1;
    } else {
      console.log(r.text);
      process.exitCode = 2;
    }
  }
} else {
  const {Then} = require('@cucumber/cucumber');
  Then('build-no-edit-turns-end-build: the no-edit Build fixture {string} ends as specified', {timeout: 250000}, function (mode, want) {
    JSON.parse(want);
    const r = run(mode, want);
    if (!r.ok) throw new Error(r.text);
  });
}
