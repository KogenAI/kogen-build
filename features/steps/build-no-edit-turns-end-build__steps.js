'use strict';
// Runs the protected no-edit Build fixture (the Go test below, of package build, overlaid at a
// path the Build must not create) through the real Build with a scripted builder, and judges it
// from `go test -json`: the one named test must run exactly once and pass.
const {spawnSync} = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const target = 'build/no_edit_turns_acceptance_test.go';
const name = 'TestNoEditTurnsAcceptance';

function run(mode, want) {
  if (fs.existsSync(path.resolve(target))) {
    return {ok: false, text: `${target} exists in the checkout; the acceptance overlay of ${name} owns that path`};
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'noedit-'));
  try {
    const source = path.join(dir, 'no_edit_turns_acceptance_test.go');
    fs.writeFileSync(source, FIXTURE.join('\n') + '\n');
    const overlay = path.join(dir, 'overlay.json');
    fs.writeFileSync(overlay, JSON.stringify({Replace: {[path.resolve(target)]: source}}));
    const args = ['test', '-json', '-overlay', overlay, './build', '-run', '^' + name + '$', '-count=1'];
    // Go resolves the overlay's keys against $PWD: make it the directory Node resolved them in.
    const env = {...process.env, PWD: process.cwd(), NOEDIT_MODE: mode};
    if (want !== undefined) env.NOEDIT_WANT = want;
    const r = spawnSync('go', args, {cwd: process.cwd(), encoding: 'utf8', env, timeout: 240000, maxBuffer: 64 * 1024 * 1024});
    const rows = (r.stdout || '').split('\n').filter(x => x.startsWith('{')).map(x => {
      try { return JSON.parse(x); } catch { return {}; }
    });
    const runs = rows.filter(x => x.Test === name && x.Action === 'run').length;
    const passes = rows.filter(x => x.Test === name && x.Action === 'pass').length;
    const output = rows.filter(x => typeof x.Output === 'string').map(x => x.Output).join('');
    const ok = r.status === 0 && runs === 1 && passes === 1;
    const text = `${name} (NOEDIT_MODE=${mode}): go ${args.join(' ')} exited ${r.status}` +
      `${r.error ? ' (' + r.error.message + ')' : ''}; ${name} ran ${runs} time(s) and passed ${passes} time(s)` +
      `${runs === 0 ? ' (absent or skipped)' : ''}\n${output}${r.stderr || ''}`;
    return {ok, text};
  } finally {
    fs.rmSync(dir, {recursive: true, force: true});
  }
}

